const forceNullForAutoTranslatedApiField = (locale, apiKeyName, generateTitle, generateDescription) => {
  if (locale === 'ar') {
    return (
      (apiKeyName === 'title' && generateTitle) ||
      (apiKeyName === 'description' && generateDescription)
    );
  }
  return (
    (apiKeyName === 'title_l1' && generateTitle) ||
    (apiKeyName === 'description_l1' && generateDescription)
  );
};

const resolveRentFrequencyIdForListingRoot = (raw, dynamicFieldDefinitions) => {
  if (raw === undefined || raw === null || raw === '') return raw;
  const def = dynamicFieldDefinitions?.find((d) => d.apiKeyName === 'rent_frequency');
  const opts = def?.options || [];
  if (!opts.length) return raw;
  const matched = findOption(opts, raw);
  return matched?.id != null ? matched.id : raw;
};

/** Resolve a scalar location id; avoid String(object) → "[object Object]". */
const coerceScalarLocationId = (v, depth = 0) => {
  if (v == null || v === '') return undefined;
  if (typeof v === 'string' || typeof v === 'number') return v;
  if (depth > 5 || typeof v !== 'object' || Array.isArray(v)) return undefined;
  return (
    coerceScalarLocationId(v.location_id, depth + 1) ??
    coerceScalarLocationId(v.id, depth + 1) ??
    coerceScalarLocationId(v.value, depth + 1)
  );
};

/** location-select: { city, location } on Formik `location-info`; ids may be on .value or values.location */
const resolveListingLocationIdFromComposite = (composite, values = {}) => {
  const fromListingRoot = () =>
    coerceScalarLocationId(values?.location) ??
    coerceScalarLocationId(values?.location?.id) ??
    coerceScalarLocationId(values?.location?.value);

  if (composite == null || composite === '') {
    return fromListingRoot();
  }

  const direct = coerceScalarLocationId(composite);
  if (direct != null && direct !== '') return direct;

  if (typeof composite !== 'object') return fromListingRoot();

  const loc = composite.location;
  const city = composite.city;
  const fromLoc =
    (loc && coerceScalarLocationId(loc)) ??
    coerceScalarLocationId(loc?.location_id) ??
    coerceScalarLocationId(loc?.id) ??
    coerceScalarLocationId(loc?.value);
  if (fromLoc != null && fromLoc !== '') return fromLoc;

  const fromCity =
    (city && coerceScalarLocationId(city)) ??
    coerceScalarLocationId(city?.location_id) ??
    coerceScalarLocationId(city?.id) ??
    coerceScalarLocationId(city?.value);
  if (fromCity != null && fromCity !== '') return fromCity;

  // Composite is a location field object (possibly cleared). Do not fall back to values.location —
  // that stays pre-filled from the listing and would resurrect a cleared selection in the payload.
  return undefined;
};

const formatDynamicFieldForApi = createFormatDynamicFieldForApi({
  resolveLocationId: resolveListingLocationIdFromComposite,
  locationInfoKeys: ['location-info'],
  slugPreferredKeys: ['sale_type', 'rent_frequency'],
  includeVideosAsListingAttributes: true,
});

const autoGeneratedListingContentPayload = ({ values, content_type, listingId, dynamicFieldDefinitions }) => {
  const isDailyRentalListing = values?.listing_purpose?.slug === 'daily-rental';
  const resolvedListingId = listingId ?? values?.id;
  const sendArea = shouldSendAreaListingFields(dynamicFieldDefinitions);
  return {
    content_type: content_type,
    purpose_name: values?.listing_purpose?.title,
    type: isDailyRentalListing
      ? values?.property_type_label
      : values?.sub_listing_type?.label || values?.listing_type?.title,
    city: values?.location?.city_id,
    location: values?.location?.title,
    ...(sendArea && {
      area: values?.area_unit?.value,
      area_unit: values?.area_unit?.id,
    }),
    furnished: isDailyRentalListing ? 'yes' : isFurnishedYes(values?.furnished) ? 'yes' : 'no',
    rental_frequency: isDailyRentalListing ? 1 : values?.listing_purpose?.title === 'Rent' && values?.rental_frequency,
    price:
      values?.listing_purpose?.title === 'Rent'
        ? values?.rental_price
          ? parseInt(values?.rental_price)
          : 0
        : values?.price
          ? parseInt(values?.price)
          : 0,
    beds: parseInt(values?.bedrooms) || null,
    baths: parseInt(values?.bathrooms) || null,
    ...(resolvedListingId != null &&
      resolvedListingId !== '' && { listing_id: String(resolvedListingId) }),
  };
};

const findFeatureById = (arr, featureId) => {
  for (const group of arr) {
    const feature = group.features.find((feature) => feature.feature_id == featureId);
    if (feature) {
      return feature?.id;
    }
  }
  return null;
};

const getListingFeatures = (featuresAmenities, listingFeatures) =>
  featuresAmenities && Object.keys(featuresAmenities)?.length
    ? Object.keys(featuresAmenities)
        .map((e) =>
          !!findFeatureById(listingFeatures, e)
            ? {
                id: findFeatureById(listingFeatures, e),
                feature_id: e,
                ...(featuresAmenities?.[e] == undefined || featuresAmenities?.[e] == false
                  ? { _destroy: true }
                  : { feature_value: featuresAmenities?.[e] === true ? 'Yes' : featuresAmenities?.[e] }),
              }
            : featuresAmenities?.[e]
              ? { feature_id: e, feature_value: featuresAmenities?.[e] === true ? 'Yes' : featuresAmenities?.[e] }
              : null,
        )
        .filter((e) => !!e)
    : [];

